bank = json.load(open(r'E:/WorkBuddy/pokemon-study-site/_bank12.json', encoding='utf-8'))
words = bank["words"]
missing = [e["chr"] for e in bank["up"] if e["chr"] not in words]
extra = sorted(set(FIX) - set(missing))
uncovered = [c for c in missing if c not in FIX]
assert not uncovered, f"FIX 未覆盖: {''.join(uncovered)}"
for c in missing:
    ws = FIX[c].split("、")
    assert len(ws) == 2 and all(c in w for w in ws), f"组词不合规: {c} -> {FIX[c]}"
    assert len(set(ws)) == 2, f"重复组词: {c}"
    words[c] = FIX[c]

# 网页源（_sc/_sohu）的值是「多个词的列表」，字库每条只需一个词 → 归一化取第一个
for c, v in list(words.items()):
    if isinstance(v, list):
        words[c] = v[0] if v else ""

# 全库体检：组词必须 ≥2 字且含本字（blankPhrase 依赖）
bad = []
for lvl in ("up", "down"):
    for e in bank[lvl]:
        w = words.get(e["chr"], "")
        if len(w) < 2 or e["chr"] not in w:
            bad.append((lvl, e["chr"], w))
assert not bad, f"组词体检失败: {bad[:20]}"

json.dump(bank, open(r'E:/WorkBuddy/pokemon-study-site/_bank12.json', 'w', encoding='utf-8'), ensure_ascii=False)
